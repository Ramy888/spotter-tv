// Serves the phone camera page over HTTPS from a Lambda function URL.
// Only the files listed here are served; everything else is a 404.
import { existsSync, readFileSync } from "node:fs";

const page = readFileSync(new URL("./public/index.html", import.meta.url), "utf8");
const config = JSON.stringify({ relayUrl: process.env.RELAY_URL });

const routes = {
  "/": { body: page, type: "text/html; charset=utf-8", cache: "no-cache" },
  "/index.html": { body: page, type: "text/html; charset=utf-8", cache: "no-cache" },
  "/config.json": { body: config, type: "application/json", cache: "no-cache" },
};

const CLIP = /^\/audio\/([a-z][a-z0-9-]{0,31})\.mp3$/;

// Voice clips (generated by voice/make-voice.mjs), served to the phone page and the TV app.
function audio(path) {
  if (path === "/audio/clips.json") {
    const file = new URL("./public/audio/clips.json", import.meta.url);
    return existsSync(file) ? { body: readFileSync(file, "utf8"), type: "application/json", cache: "max-age=3600" } : undefined;
  }
  const id = CLIP.exec(path)?.[1];
  if (!id) return undefined;
  const file = new URL(`./public/audio/${id}.mp3`, import.meta.url);
  if (!existsSync(file)) return undefined;
  return { body: readFileSync(file).toString("base64"), type: "audio/mpeg", cache: "max-age=86400", base64: true };
}

export async function handler(event) {
  const isGet = event.requestContext?.http?.method === "GET";
  const route = isGet ? routes[event.rawPath] ?? audio(event.rawPath) : undefined;
  if (!route) return { statusCode: 404, headers: { "content-type": "text/plain" }, body: "not found" };
  return {
    statusCode: 200,
    headers: {
      "content-type": route.type,
      "cache-control": route.cache,
      "x-content-type-options": "nosniff",
      "referrer-policy": "no-referrer",
    },
    body: route.body,
    isBase64Encoded: Boolean(route.base64),
  };
}
